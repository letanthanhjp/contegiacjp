/* =====================================================
   NGÔN NGỮ HIỆN TẠI
   ===================================================== */

let currentLanguage =
    localStorage.getItem("contegiacjp-language") || "vi";


/* =====================================================
   LẤY BẢN DỊCH
   ===================================================== */

function translateText(text){

    if(!text){
        return text;
    }

    const dictionary =
        translations[currentLanguage];

    if(dictionary[text] !== undefined){
        return dictionary[text];
    }

    return text;
}


/* =====================================================
   DỊCH TEXT NODE
   ===================================================== */

function translateTextNodes(root){

    const walker =
        document.createTreeWalker(
            root,
            NodeFilter.SHOW_TEXT,
            {
                acceptNode:function(node){

                    const parent =
                        node.parentElement;

                    if(!parent){
                        return NodeFilter.FILTER_REJECT;
                    }

                    const tag =
                        parent.tagName;

                    if(
                        tag === "SCRIPT" ||
                        tag === "STYLE" ||
                        tag === "NOSCRIPT" ||
                        tag === "TEXTAREA"
                    ){
                        return NodeFilter.FILTER_REJECT;
                    }

                    return NodeFilter.FILTER_ACCEPT;
                }
            }
        );


    const nodes = [];

    let node;

    while(
        node = walker.nextNode()
    ){
        nodes.push(node);
    }


    nodes.forEach(function(textNode){

        const original =
            textNode.nodeValue;

        const trimmed =
            original.trim();

        if(!trimmed){
            return;
        }


        const translated =
            translateText(trimmed);


        if(translated !== trimmed){

            textNode.nodeValue =
                original.replace(
                    trimmed,
                    translated
                );

        }

    });

}


/* =====================================================
   DỊCH PLACEHOLDER
   ===================================================== */

function translatePlaceholders(){

    document
        .querySelectorAll(
            "input[placeholder], textarea[placeholder]"
        )
        .forEach(function(element){

            const original =
                element.placeholder;

            const translated =
                translateText(original);

            if(translated !== original){

                element.placeholder =
                    translated;

            }

        });

}


/* =====================================================
   DỊCH TITLE
   ===================================================== */

function translateTitles(){

    document
        .querySelectorAll("[title]")
        .forEach(function(element){

            const original =
                element.title;

            const translated =
                translateText(original);

            if(translated !== original){

                element.title =
                    translated;

            }

        });

}


/* =====================================================
   ÁP DỤNG NGÔN NGỮ
   ===================================================== */

function applyLanguage(){

    translateTextNodes(document.body);

    translatePlaceholders();

    translateTitles();


    /* ================= LANGUAGE SELECTOR ================= */

    const selector =
        document.getElementById(
            "language-selector"
        );

    if(selector){

        selector.value =
            currentLanguage;

    }

}


/* =====================================================
   ĐỔI NGÔN NGỮ
   ===================================================== */

function setLanguage(language){

    if(!translations[language]){
        return;
    }


    currentLanguage =
        language;


    localStorage.setItem(
        "contegiacjp-language",
        language
    );


    applyLanguage();

}


/* =====================================================
   TỰ ĐỘNG DỊCH NỘI DUNG MỚI
   ===================================================== */

const languageObserver =
    new MutationObserver(function(){

        applyLanguage();

    });


/* =====================================================
   KHỞI ĐỘNG
   ===================================================== */

document.addEventListener(
    "DOMContentLoaded",
    function(){

        applyLanguage();


        languageObserver.observe(
            document.body,
            {
                childList:true,
                subtree:true
            }
        );

    }
);